package cn.blockforge.generated.silentknock.spa;

import cn.blockforge.generated.silentknock.SilentSpaClient;
import net.fabricmc.loader.api.FabricLoader;

import javax.crypto.Cipher;
import javax.crypto.Mac;
import javax.crypto.spec.GCMParameterSpec;
import javax.crypto.spec.SecretKeySpec;
import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.PosixFilePermissions;
import java.security.SecureRandom;
import java.util.Base64;
import java.util.Locale;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * 模组保存 / 读取 SPA 配置文件（fwknoprc）时的落盘工具。
 *
 * <p><b>现在写盘是明文</b>：生成的就是标准 fwknoprc 文本，用记事本就能看，
 * 也能直接复制到别的电脑、或者给 fwknop 客户端用。密钥本身就是一串 Base64，
 * 加密反而让文件没法通用，所以只在文件权限上收紧（类 Unix 系统上设成 600）。
 *
 * <p>类名里的 “Vault” 是历史遗留：更早的版本把密钥文件加密过，
 * 那种旧文件（第一行 {@code #SILENTSPA-ENC v1}）现在仍然能读：
 * <pre>
 * #SILENTSPA-ENC v1
 * SALT: &lt;Base64&gt;
 * IV:   &lt;Base64&gt;
 * DATA: &lt;Base64&gt;
 * </pre>
 * 加密算法是 AES-256-GCM，本机主密钥在 {@code config/silent_knock.keyring}。
 * 旧文件读的时候自动解密；新版本不会再生成这种文件。
 */
public final class SpaKeyVault {
    /** 加密文件第一行固定写成这个，用来和普通 fwknop 文本区分。 */
    public static final String HEADER = "#SILENTSPA-ENC v1";

    private static final String AAD = "SILENTSPA-ENC v1";
    private static final int SALT_LENGTH = 16;
    private static final int IV_LENGTH = 12;
    private static final int TAG_BITS = 128;
    private static final int MASTER_KEY_LENGTH = 32;
    private static final Pattern LABEL_LINE =
            Pattern.compile("^([A-Za-z][A-Za-z0-9_]*)\\s*:\\s*(\\S.*)$");
    private static final SecureRandom RANDOM = new SecureRandom();

    private SpaKeyVault() {
    }

    /** 模组自己生成 / 保存密钥文件的目录：{@code .minecraft/silentknock/keys}。 */
    public static Path keysDirectory() {
        return FabricLoader.getInstance().getGameDir().resolve("silentknock").resolve("keys");
    }

    /** 本机主密钥的路径。 */
    public static Path keyringPath() {
        return FabricLoader.getInstance().getConfigDir().resolve("silent_knock.keyring");
    }

    /** 内容是不是本模组生成的加密文件。 */
    public static boolean isEncrypted(String content) {
        if (content == null) {
            return false;
        }
        for (String raw : content.split("\\R")) {
            String line = raw.strip();
            if (line.isEmpty()) {
                continue;
            }
            return line.startsWith("#SILENTSPA-ENC");
        }
        return false;
    }

    /**
     * 把明文密钥内容加密成可以直接写盘的文本。
     *
     * @throws SpaKeyException 本机主密钥读写失败时
     */
    public static String encrypt(String plaintext) throws SpaKeyException {
        try {
            byte[] salt = randomBytes(SALT_LENGTH);
            byte[] iv = randomBytes(IV_LENGTH);
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.ENCRYPT_MODE, fileKey(masterKey(true), salt),
                    new GCMParameterSpec(TAG_BITS, iv));
            cipher.updateAAD(AAD.getBytes(StandardCharsets.UTF_8));
            byte[] data = cipher.doFinal(plaintext.getBytes(StandardCharsets.UTF_8));

            StringBuilder out = new StringBuilder(256);
            out.append(HEADER).append('\n');
            out.append("# 由 SilentSPA 生成：内容已加密，只有创建它的这台电脑能解开。\n");
            out.append("# Generated by SilentSPA: encrypted, only the machine that created it can open it.\n");
            out.append("# 要换电脑用，请把 config/silent_knock.keyring 一起复制过去。\n");
            out.append("SALT: ").append(encode(salt)).append('\n');
            out.append("IV: ").append(encode(iv)).append('\n');
            out.append("DATA: ").append(encode(data)).append('\n');
            return out.toString();
        } catch (SpaKeyException e) {
            throw e;
        } catch (Exception e) {
            throw new SpaKeyException("silent_knock.key.enc_failed", e.toString());
        }
    }

    /**
     * 解密 {@link #encrypt(String)} 产生的文本，返回里面的明文。
     *
     * @throws SpaKeyException 本机没有主密钥 / 文件被改过 / 是从别的电脑复制来的
     */
    public static String decrypt(String content) throws SpaKeyException {
        byte[] salt = null;
        byte[] iv = null;
        byte[] data = null;
        if (content != null) {
            for (String raw : content.split("\\R")) {
                Matcher matcher = LABEL_LINE.matcher(raw.strip());
                if (!matcher.matches()) {
                    continue;
                }
                String key = matcher.group(1).toUpperCase(Locale.ROOT);
                String value = matcher.group(2).strip();
                switch (key) {
                    case "SALT" -> salt = decodeOrNull(value);
                    case "IV" -> iv = decodeOrNull(value);
                    case "DATA" -> data = decodeOrNull(value);
                    default -> {
                        // 注释、其它行都忽略
                    }
                }
            }
        }
        if (salt == null || iv == null || data == null) {
            throw new SpaKeyException("silent_knock.key.enc_damaged");
        }
        try {
            Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
            cipher.init(Cipher.DECRYPT_MODE, fileKey(masterKey(false), salt),
                    new GCMParameterSpec(TAG_BITS, iv));
            cipher.updateAAD(AAD.getBytes(StandardCharsets.UTF_8));
            return new String(cipher.doFinal(data), StandardCharsets.UTF_8);
        } catch (SpaKeyException e) {
            throw e;
        } catch (Exception e) {
            // GCM 校验失败基本只有两种可能：keyring 换了，或者文件是从别的电脑复制来的
            throw new SpaKeyException("silent_knock.key.enc_wrong_key");
        }
    }

    /**
     * 把 SPA 配置文本原样写进 {@link #keysDirectory()}。
     *
     * @param fileName 玩家输入的文件名，会自动补 {@code .fwknoprc}、去掉非法字符、重名自动加序号
     * @param content  要写进去的 fwknoprc 文本（明文）
     * @return 真正写到磁盘上的路径
     */
    public static Path write(String fileName, String content) throws SpaKeyException {
        Path directory = keysDirectory();
        String safeName = sanitizeFileName(fileName);
        try {
            Files.createDirectories(directory);
            Path target = uniqueTarget(directory, safeName);
            Files.writeString(target, content, StandardCharsets.UTF_8);
            restrictPermissions(target);
            SilentSpaClient.LOGGER.info("[SPA] 已写入 SPA 配置文件：{}", target);
            return target;
        } catch (IOException | RuntimeException e) {
            throw new SpaKeyException("silent_knock.key.write_failed", e.toString());
        }
    }

    /** 清理玩家输入的文件名：去掉路径分隔符等不能出现在文件名里的字符，补上 {@code .fwknoprc}。 */
    public static String sanitizeFileName(String raw) {
        String name = raw == null ? "" : raw.strip();
        name = name.replaceAll("[\\\\/:*?\"<>|\\s]+", "_");
        while (name.startsWith(".")) {
            name = name.substring(1);
        }
        if (name.isEmpty()) {
            name = "spa-config";
        }
        String lower = name.toLowerCase(Locale.ROOT);
        if (!lower.endsWith(".fwknoprc") && !lower.endsWith(".spa")
                && !lower.endsWith(".conf") && !lower.endsWith(".txt")) {
            name = name + ".fwknoprc";
        }
        if (name.length() > 64) {
            name = name.substring(0, 64);
        }
        return name;
    }

    /** 文件名去掉扩展名，当作 fwknoprc 的段名。 */
    public static String sectionName(String fileName) {
        String name = sanitizeFileName(fileName);
        int dot = name.lastIndexOf('.');
        if (dot > 0) {
            name = name.substring(0, dot);
        }
        name = name.replaceAll("[^A-Za-z0-9._-]", "_");
        return name.isBlank() ? "default" : name;
    }

    private static Path uniqueTarget(Path directory, String fileName) {
        Path target = directory.resolve(fileName);
        if (!Files.exists(target)) {
            return target;
        }
        String base = fileName;
        String extension = "";
        int dot = fileName.lastIndexOf('.');
        if (dot > 0) {
            base = fileName.substring(0, dot);
            extension = fileName.substring(dot);
        }
        for (int i = 2; i < 10_000; i++) {
            Path candidate = directory.resolve(base + "-" + i + extension);
            if (!Files.exists(candidate)) {
                return candidate;
            }
        }
        return directory.resolve(base + "-" + System.currentTimeMillis() + extension);
    }

    /**
     * 读本机主密钥。
     *
     * @param create true 表示没有就新建一把（只有在创建密钥文件时才允许）
     */
    private static byte[] masterKey(boolean create) throws SpaKeyException {
        Path path = keyringPath();
        byte[] existing = readKeyring(path);
        if (existing != null) {
            return existing;
        }
        if (!create) {
            throw new SpaKeyException("silent_knock.key.enc_no_keyring");
        }
        byte[] fresh = randomBytes(MASTER_KEY_LENGTH);
        try {
            Files.createDirectories(path.getParent());
            Files.writeString(path,
                    "# SilentSPA 本机主密钥：用来解密 .minecraft/silentknock/keys 里的密钥文件。\n"
                            + "# 请不要删除、不要外传；换电脑时和密钥文件一起复制过去。\n"
                            + "# SilentSPA local keyring: keep it private, copy it with your .spa files.\n"
                            + encode(fresh) + "\n",
                    StandardCharsets.UTF_8);
            restrictPermissions(path);
            SilentSpaClient.LOGGER.info("[SPA] 已生成本机密钥环：{}", path);
        } catch (IOException | RuntimeException e) {
            throw new SpaKeyException("silent_knock.key.enc_failed", e.toString());
        }
        return fresh;
    }

    private static byte[] readKeyring(Path path) {
        if (!Files.isRegularFile(path)) {
            return null;
        }
        try {
            for (String raw : Files.readAllLines(path, StandardCharsets.UTF_8)) {
                String line = raw.strip();
                if (line.isEmpty() || line.startsWith("#")) {
                    continue;
                }
                byte[] key = decodeOrNull(line);
                return key != null && key.length >= 16 ? key : null;
            }
        } catch (IOException | RuntimeException e) {
            SilentSpaClient.LOGGER.warn("[SPA] 本机密钥环读取失败：{}", e.toString());
        }
        return null;
    }

    /** 用主密钥 + 每个文件自己的盐派生文件密钥。 */
    private static SecretKeySpec fileKey(byte[] master, byte[] salt) throws Exception {
        Mac mac = Mac.getInstance("HmacSHA256");
        mac.init(new SecretKeySpec(master, "HmacSHA256"));
        mac.update(salt);
        mac.update(AAD.getBytes(StandardCharsets.UTF_8));
        return new SecretKeySpec(mac.doFinal(), "AES");
    }

    private static byte[] randomBytes(int length) {
        byte[] bytes = new byte[length];
        RANDOM.nextBytes(bytes);
        return bytes;
    }

    private static String encode(byte[] bytes) {
        return Base64.getEncoder().encodeToString(bytes);
    }

    private static byte[] decodeOrNull(String value) {
        try {
            return Base64.getDecoder().decode(value.replaceAll("\\s+", ""));
        } catch (IllegalArgumentException e) {
            return null;
        }
    }

    /** 尽量把文件权限收紧成只有自己能读写（Windows 上不支持就跳过）。 */
    private static void restrictPermissions(Path path) {
        try {
            Files.setPosixFilePermissions(path, PosixFilePermissions.fromString("rw-------"));
        } catch (UnsupportedOperationException | IOException ignored) {
            // Windows 等不支持 POSIX 权限的平台上忽略
        }
    }
}
